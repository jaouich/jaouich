// Black Boxes: 1-10 Pi, fixed contents, numbered cards (up to 1,000,000), burn, gift/market work on them. Fresh harness.
const B = "http://localhost:3457";
const post = (p, b, tok) => fetch(B + p, { method: "POST", headers: { "Content-Type": "application/json", ...(tok ? { Authorization: "Bearer " + tok } : {}) }, body: typeof b === "string" ? b : JSON.stringify(b) }).then((r) => r.json());
const get = (p, tok) => fetch(B + p, { headers: tok ? { Authorization: "Bearer " + tok } : {} }).then((r) => r.json());
const sql = (q) => post("/__test/sql", q);
let pass = 0, fail = 0;
const ok = (c, m, x) => { console.log((c ? "PASS  " : "FAIL  ") + m + (c || x === undefined ? "" : " -> " + JSON.stringify(x))); c ? pass++ : fail++; };
global.window = global; await import("../public/logic.js"); await import("../public/kombat-logic.js"); await import("../public/catalog-logic.js");
const L = globalThis.OasisLogic, KL = globalThis.KombatLogic, BB = L.BBOX;
ok(BB.TIERS.length === 10 && BB.TIERS.every((t, i) => t.p === i + 1), "ten boxes, 1 to 10 Pi");
ok(BB.TIERS.every((t, i) => !i || (t.dates > BB.TIERS[i - 1].dates && t.jry > BB.TIERS[i - 1].jry && t.coins > BB.TIERS[i - 1].coins)), "every box is better than the one before");
ok(KL.COLLECTIBLES.filter((c) => c.pi).length === 10 && KL.COLLECTIBLES.filter((c) => c.pi).every((c) => c.max === 1000000), "10 collectible cards with 1,000,000 copies each");
const cat = globalThis.CatalogLogic && globalThis.CatalogLogic.items ? globalThis.CatalogLogic.items() : null;
ok(!cat || !cat.some((x) => /^box/.test(x.id || x.key || "")), "boxes are not part of the Catalog album");
const C = (await post("/api/auth", { accessToken: "tokC" })).session, D = (await post("/api/auth", { accessToken: "tokD" })).session;
const uC = (await sql("SELECT uid FROM users WHERE username='carol'"))[0].uid, uD = (await sql("SELECT uid FROM users WHERE username='dina'"))[0].uid;
await post("/api/me", {}, C);
const pay = async (id, uid, amount, tier, h) => {
  await fetch(B + "/__test/pay", { method: "POST", body: JSON.stringify({ id, uid, amount, type: "bbox", tier, txid: "t" + id }) });
  const a = await post("/api/payments/approve", { paymentId: id }, h); if (a.error) return a;
  return post("/api/payments/complete", { paymentId: id, txid: "t" + id }, h);
};
ok((await pay("b0", uC, 3, 5, C)).error === "badPayment", "wrong amount for the box is refused");
ok((await pay("b00", uC, 11, 11, C)).error === "badPayment", "there is no box 11");
const st0 = async () => (await sql(`SELECT json_extract(json,'$.dates') AS d FROM state WHERE uid='${uC}'`))[0].d;
const jry0 = async (u) => (await sql(`SELECT COALESCE(jry_pts,0) AS j FROM users WHERE uid='${u}'`))[0].j;
let d0 = await st0(), j0 = await jry0(uC);
let r = await pay("b1", uC, 7, 7, C);
ok(r.ok !== false && !r.error, "a 7 Pi box is accepted", r);
const T7 = BB.of(7);
ok((await st0()) - d0 === T7.dates && (await jry0(uC)) - j0 === T7.jry, "fixed contents arrive (dates, JRY points)", [(await st0()) - d0, (await jry0(uC)) - j0]);
const st = (await get("/api/me", C)).state;
ok(st.animals.some((a) => a.rarity === 3 && a.from === "bbox"), "box 7 includes a legendary camel");
const vc = (await sql(`SELECT vipc_until, mult_id, mult_until FROM users WHERE uid='${uC}'`))[0];
ok(vc.vipc_until > Date.now() + 1.5 * 86400000 && vc.mult_id === "x2" && vc.mult_until > Date.now() + 6 * 86400000, "box 7 includes VIP Club days and an x2 multiplier");
let items = await sql(`SELECT id, kind, edition FROM nft_items WHERE owner='${uC}' AND kind LIKE 'box%'`);
ok(items.length === 1 && items[0].kind === "box7" && items[0].edition === 1, "a numbered card #1 is minted", items);
await pay("b2", uD, 7, 7, D);
items = await sql(`SELECT edition FROM nft_items WHERE kind='box7' ORDER BY edition`);
ok(items.map((x) => x.edition).join() === "1,2", "the next buyer gets #2");
const op = await get("/api/bbox", C);
ok(op.opens.length === 1 && op.opens[0].tier === 7 && op.opens[0].edition === 1 && op.minted["7"] === 2, "my openings are listed", op);
// the same payment can't open twice
await post("/api/payments/complete", { paymentId: "b1", txid: "tb1" }, C);
ok((await sql("SELECT COUNT(*) AS n FROM nft_items WHERE kind='box7'"))[0].n === 2, "completing twice does not mint twice");
// the card is a normal collectible: gift, then the new owner can burn it
const cid = items.length && (await sql(`SELECT id FROM nft_items WHERE kind='box7' AND edition=1`))[0].id;
ok((await post("/api/nft/mint", { kind: "box7" }, C)).error === "k.nftPaid", "boxes can't be minted with coins");
r = await post("/api/nft/list", { id: cid, price: 5000, cur: "coins" }, C);
ok(r.ok, "the card can be listed for points");
await post("/api/nft/list", { id: cid, price: null }, C);
ok((await post("/api/bbox/burn", { id: cid }, D)).error, "only the owner can burn");
const dd = async () => (await sql(`SELECT json_extract(json,'$.dates') AS d FROM state WHERE uid='${uC}'`))[0].d;
const b0 = await dd();
r = await post("/api/bbox/burn", { id: cid }, C);
ok(r.ok && r.dates === Math.floor(T7.dates * BB.BURN) && (await dd()) - b0 === r.dates, "burning pays 20% of the dates and destroys the card", r);
ok((await sql(`SELECT COUNT(*) AS n FROM nft_items WHERE id=${cid}`))[0].n === 0, "the burned card is gone");
await pay("b3", uC, 7, 7, C);
ok((await sql(`SELECT edition FROM nft_items WHERE owner='${uC}' AND kind='box7'`))[0].edition === 3, "burned numbers are never reused");
console.log(`== ${pass} passed, ${fail} failed`);
