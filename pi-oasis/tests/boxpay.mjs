// Paying inside the app with the Pi waiting in the box. Fresh harness.
const B = "http://localhost:3457";
const post = (p, b, h = {}) => fetch(B + p, { method: "POST", headers: { "Content-Type": "application/json", ...h }, body: JSON.stringify(b) }).then((r) => r.json());
const get = (p, h = {}) => fetch(B + p, { headers: h }).then((r) => r.json());
const sql = (q) => fetch(B + "/__test/sql", { method: "POST", body: q }).then((r) => r.json());
const exec = (q) => fetch(B + "/__test/exec", { method: "POST", body: q });
let pass = 0, fail = 0;
const ok = (c, m, x) => { console.log((c ? "PASS  " : "FAIL  ") + m + (c || x === undefined ? "" : " -> " + JSON.stringify(x))); c ? pass++ : fail++; };
const H = async (tok, ref) => ({ Authorization: "Bearer " + (await post("/api/auth", { accessToken: tok, ref })).session });
const HA = await H("tokA"), HB = await H("tokB", "alice"), HC = await H("tokC");
const uB = (await sql("SELECT uid FROM users WHERE username='bob'"))[0].uid;
const row = (id, amt, status = "new", kind = "prize", t = 1) => `INSERT INTO payouts (id, kind, ref, uid, amount, memo, status, created_at, updated_at) VALUES ('${id}','${kind}','r${id}','${uB}',${amt},'x','${status}',${t},${t});`;
await exec(row("a", 3) + row("b", 4.5) + row("c", 9, "created") + row("d", 2, "completed"));
let me = await get("/api/me", HB);
ok(me.account.piWaiting === 7.5, "the account shows 7.5 Pi waiting (new rows only)", me.account.piWaiting);
const spend = (md, amount, h = HB) => post("/api/box/spend", { metadata: md, amount }, h);
const pool0 = (await sql("SELECT COALESCE(SUM(prize_pool),0) AS n FROM weeks"))[0].n;
const ref0 = (await sql("SELECT ref_balance FROM users WHERE username='alice'"))[0].ref_balance;
ok((await spend({ type: "vipclub" }, 4)).error === "badPayment", "wrong price refused");
ok((await spend({ type: "p2p", offer: 1 }, 5)).error === "box.notHere", "not for player-to-player trades");
ok((await spend({ type: "jry" }, 5)).error === "box.notHere", "not for testJRY");
ok((await spend({ type: "vipclub" }, 5, HC)).error === "box.low", "nothing waiting: refused");
let r = await spend({ type: "vipclub" }, 5);
ok(r.ok && r.account.vipcUntil > Date.now(), "VIP Club paid from the box (5 Pi)", r.error);
const rows = await sql("SELECT id, amount, status FROM payouts WHERE uid = '" + uB + "' ORDER BY id");
ok(rows.find((x) => x.id === "a").status === "spent" && Math.abs(rows.find((x) => x.id === "b").amount - 2.5) < 1e-9, "row a used up, row b reduced to 2.5", rows);
ok(rows.find((x) => x.id === "c").status === "created" && rows.find((x) => x.id === "c").amount === 9, "a payout already in flight is untouched");
ok(r.account.piWaiting === 2.5, "2.5 Pi still waiting", r.account.piWaiting);
ok((await sql("SELECT status FROM payments WHERE id LIKE 'box-%'"))[0].status === "box", "recorded as a box payment (not a Pi payment)");
ok((await sql("SELECT COALESCE(SUM(prize_pool),0) AS n FROM weeks"))[0].n === pool0, "nothing added to the weekly prize pool");
ok((await sql("SELECT ref_balance FROM users WHERE username='alice'"))[0].ref_balance === ref0, "the inviter gets no commission on box money");
const hall = await get("/api/vipc", HB);
ok(!hall.hall.some((x) => x.username === "bob"), "box money does not count in the Hall of Glory (real Pi only)");
ok((await spend({ type: "vipclub" }, 5)).error === "box.low", "2.5 Pi is not enough for 5");
const box = await get("/api/box", HB);
ok(box.piBox.waiting === 2.5 + 9, "the box shows what is left (incl. the one in flight)", box.piBox.waiting);
// multiplier lower guard + a royal card
await exec(row("e", 200));
ok((await spend({ type: "mult", mult: "x10" }, 100)).ok, "x10 multiplier paid from the box");
ok((await spend({ type: "mult", mult: "x2" }, 10)).error === "multLower", "no smaller multiplier while a bigger one runs");
r = await spend({ type: "royal", tier: "r25", ed: 1 }, 25);
ok(r.ok && (await sql("SELECT uid FROM royal_cards WHERE tier='r25' AND ed=1"))[0].uid === uB, "a royal card bought from the box");
ok((await spend({ type: "royal", tier: "r25", ed: 1 }, 25, HA)).error === "rc.taken", "the same copy cannot be bought twice");
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
