// Gift codes. Start tests/harness.mjs first.
const B = "http://localhost:3457";
const post = (p, b, h = {}) => fetch(B + p, { method: "POST", headers: { "Content-Type": "application/json", ...h }, body: JSON.stringify(b) }).then((r) => r.text().then((t) => { try { return { s: r.status, ...JSON.parse(t) }; } catch { return { s: r.status, t }; } }));
const exec = (q) => fetch(B + "/__test/exec", { method: "POST", body: q });
let pass = 0, fail = 0;
const ok = (c, m) => { console.log((c ? "PASS  " : "FAIL  ") + m); c ? pass++ : fail++; };
const H = async (tok) => ({ Authorization: "Bearer " + (await post("/api/auth", { accessToken: tok })).session });
const HA = await H("tokA"), HB = await H("tokB"), HC = await H("tokC");
ok((await post("/api/admin/codes", { action: "create", kind: "dates", amount: 500, count: 3 }, HB)).s === 403, "only the owner makes codes");
let r = await post("/api/admin/codes", { action: "create", kind: "dates", amount: 500, uses: 1, count: 3, days: 30 }, HA);
ok(r.made.length === 3 && r.made.every((c) => /^JRY-[A-Z2-9]{10}$/.test(c)), "3 random single-use codes");
const [c1] = r.made;
const me = (h) => fetch(B + "/api/me", { headers: h }).then((x) => x.json());
const d0 = (await me(HB)).state.dates;
r = await post("/api/code/redeem", { code: c1.toLowerCase() }, HB);
ok(r.ok && r.kind === "dates" && r.state.dates === d0 + 500, "code works (any letter case): +500 dates");
ok(r.state.week.score === 0, "code dates don't count in the weekly ranking");
ok((await post("/api/code/redeem", { code: c1 }, HB)).error === "code.used", "same player can't use it twice");
ok((await post("/api/code/redeem", { code: c1 }, HC)).error === "code.empty", "single-use code is used up");
ok((await post("/api/code/redeem", { code: "NOPE1234" }, HB)).error === "code.bad", "unknown code refused");
r = await post("/api/admin/codes", { action: "create", kind: "spins", amount: 3, uses: 2, code: "jerry2026" }, HA);
ok(r.made[0] === "JERRY2026", "custom code with 2 uses");
ok((await post("/api/admin/codes", { action: "create", kind: "spins", amount: 3, uses: 2, code: "JERRY2026" }, HA)).error === "code.exists", "custom code can't be created twice");
const s0 = (await me(HC)).account.wheelSpins;
r = await post("/api/code/redeem", { code: "JERRY2026" }, HC);
ok(r.ok && r.account.wheelSpins === s0 + 3, "spins code: +3 wheel spins");
ok((await post("/api/code/redeem", { code: "JERRY2026" }, HB)).ok, "second player uses the 2nd use");
ok((await post("/api/code/redeem", { code: "JERRY2026" }, HA)).error === "code.empty", "no 3rd use");
r = await post("/api/admin/codes", { action: "create", kind: "jry", amount: 50, uses: 10, code: "OLD-CODE" }, HA);
await exec("UPDATE codes SET expires_at = 1 WHERE code = 'OLD-CODE'");
ok((await post("/api/code/redeem", { code: "OLD-CODE" }, HB)).error === "code.expired", "expired code refused");
r = await post("/api/admin/codes", { action: "delete", code: "OLD-CODE" }, HA);
ok(!r.list.some((c) => c.code === "OLD-CODE"), "owner can delete a code");
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
