// The Court: titles by total real Pi paid, per-title multiplier and daily gift, overtaken messages. Fresh harness.
const B = "http://localhost:3457";
const post = (p, b, h = {}) => fetch(B + p, { method: "POST", headers: { "Content-Type": "application/json", ...h }, body: JSON.stringify(b) }).then((r) => r.json());
const get = (p, h = {}) => fetch(B + p, { headers: h }).then((r) => r.json());
const sql = (q) => fetch(B + "/__test/sql", { method: "POST", body: q }).then((r) => r.json());
const exec = (q) => fetch(B + "/__test/exec", { method: "POST", body: q });
const notifs = () => get("/__test/notifs");
let pass = 0, fail = 0;
const ok = (c, m, x) => { console.log((c ? "PASS  " : "FAIL  ") + m + (c || x === undefined ? "" : " -> " + JSON.stringify(x))); c ? pass++ : fail++; };
const H = async (tok) => ({ Authorization: "Bearer " + (await post("/api/auth", { accessToken: tok })).session });
const hs = {}; for (const [n, t] of [["alice", "tokA"], ["bob", "tokB"], ["carol", "tokC"], ["dina", "tokD"], ["emad", "tokE"], ["fatima", "tokF"]]) hs[n] = await H(t);
const uid = async (n) => (await sql(`SELECT uid FROM users WHERE username='${n}'`))[0].uid;
const U = {}; for (const n of Object.keys(hs)) U[n] = await uid(n);
global.window = global; await import("../public/logic.js"); const C = globalThis.OasisLogic.COURT;
const payNow = (id, n, amt, t) => exec(`INSERT INTO payments (id, uid, amount, status, created_at) VALUES ('${id}', '${U[n]}', ${amt}, 'completed', ${t});`);
ok(C.titleOf(1, 5).id === "emperor" && C.titleOf(2, 5).id === "prince" && C.titleOf(3, 5).id === "vizier" && C.titleOf(4, 5).id === "emir" && C.titleOf(10, 1).id === "emir" && C.titleOf(11, 1).id === "notable" && C.titleOf(0, 0).id === "citizen", "titles by rank");
ok(C.voteWeight(0) === 1 && C.voteWeight(40) === 41 && C.voteWeight(9999) === 501, "vote weight: 1 + Pi paid, capped at 500");
let lb = await get("/api/leaderboard", hs.dina);
ok(lb.court.length === 0 && !lb.king.username, "nobody paid: empty court");
await payNow("a1", "alice", 100, 1000); await payNow("b1", "bob", 60, 2000); await payNow("c1", "carol", 30, 3000); await payNow("d1", "dina", 12, 4000); await payNow("e1", "emad", 5, 5000);
await exec(`INSERT INTO payments (id, uid, amount, status, created_at) VALUES ('boxx', '${U.fatima}', 900, 'box', 6000);`); // box money does not count
lb = await get("/api/leaderboard", hs.fatima);
ok(lb.court.map((x) => x.username + ":" + x.title).join() === "alice:emperor,bob:prince,carol:vizier", "top 3 = Emperor, Crown Prince, Grand Vizier", lb.court);
const mult = async (n) => ((await get("/api/me", hs[n])).account.mult || {}).f || 0;
ok((await mult("alice")) === 3 && (await mult("bob")) === 2 && (await mult("carol")) === 1.5 && (await mult("dina")) === 0, "x3 / x2 / x1.5, Emirs and others none");
const claim = (n) => post("/api/court/claim", {}, hs[n]);
const coins = async (n) => { const r = await claim(n); return r.coins; };
ok((await coins("alice")) === 10000 && (await coins("bob")) === 6000 && (await coins("carol")) === 4000 && (await coins("dina")) === 2000, "daily coins by title: 10,000 / 6,000 / 4,000 / 2,000");
ok((await claim("alice")).error === "court.done", "once a day");
ok((await claim("fatima")).error === "court.none", "no title: nothing to claim");
let n = await notifs();
ok(n.some((x) => /new title|لقبك الجديد/.test(x.title)), "the new title holders were told");
ok(n.filter((x) => /new Emperor|إمبراطور جديد/.test(x.title)).length >= 1, "everybody is told about the new Emperor");
// overtaking: carol pays 40 -> 70, passes bob (60)
await payNow("c2", "carol", 40, 7000);
lb = await get("/api/leaderboard", hs.fatima);
ok(lb.court[1].username === "carol" && lb.court[2].username === "bob", "carol (70) passes bob (60)", lb.court);
n = await notifs();
ok(n.some((x) => /took your place|أخذ مكانك/.test(x.title)), "the overtaken player gets a message");
ok((await mult("carol")) === 2 && (await mult("bob")) === 1.5, "multipliers follow the new titles");
// ---- Houses ----
const payHouse = async (n, id, amount, house) => { await fetch(B + "/__test/pay", { method: "POST", body: JSON.stringify({ id, uid: U[n], amount, type: "house", house, txid: "t" + id }) }); const a = await post("/api/payments/approve", { paymentId: id }, hs[n]); if (a.error) return a; return post("/api/payments/complete", { paymentId: id, txid: "t" + id }, hs[n]); };
ok((await payHouse("emad", "h0", 1, { name: "Small House", emoji: "🌴", fee: 1 })).error === "house.fee", "1 Pi is only for players who already paid 10 Pi or more (emad paid 5)");
ok((await payHouse("emad", "h1", 3, { name: "Small House", emoji: "🌴", fee: 3 })).error === "badPayment", "only 10 or 1 Pi");
ok((await payHouse("emad", "h2", 10, { name: "x", emoji: "🌴", fee: 10 })).error === "badPayment", "bad name refused");
let r = await payHouse("emad", "h3", 10, { name: "Dune Riders", emoji: "🐪", fee: 10 });
ok(r.ok, "emad founds a House for 10 Pi");
ok((await payHouse("alice", "h4", 1, { name: "dune riders", emoji: "🌴", fee: 1 })).error === "house.taken", "name already taken");
r = await payHouse("alice", "h5", 1, { name: "Golden Oasis", emoji: "🌴", fee: 1 });
ok(r.ok, "alice (paid 100) founds a House for 1 Pi");
ok((await payHouse("alice", "h6", 1, { name: "Second Home", emoji: "🌴", fee: 1 })).error === "house.already", "one House at a time");
let hb = await get("/api/houses", hs.fatima);
ok(hb.houses.length === 2 && hb.fee === 10 && hb.houses[0].name === "Golden Oasis" && hb.houses[0].score === 101, "ranking: Golden Oasis = alice's total (100 + her 1 Pi House payment)", hb.houses);
await post("/api/houses/join", { id: hb.houses[0].id }, hs.bob);
hb = await get("/api/houses", hs.fatima);
ok(hb.houses[0].members === 2 && hb.houses[0].score === 161, "bob joins: members 2, score 161", hb.houses[0]);
ok((await post("/api/houses/join", { id: hb.houses[1].id }, hs.bob)).error === "house.already", "cannot join a second House");
await post("/api/houses/join", { id: hb.houses[0].id }, hs.fatima);
r = await claim("fatima");
ok(r.ok && r.coins === 1000 && r.parts.house === 1000, "members of the leading House get 1,000 coins a day", r);
await post("/api/houses/leave", {}, hs.fatima);
ok((await post("/api/houses/join", { id: hb.houses[0].id }, hs.fatima)).error === "house.wait", "24 h wait after leaving");
await post("/api/houses/leave", {}, hs.alice);
hb = await get("/api/houses", hs.bob);
ok(hb.mine && hb.mine.owner === true, "the owner left: the House passes to its biggest supporter (bob)", hb.mine);
// ---- Votes ----
const mkPoll = (n, extra = {}) => post("/api/decrees/create", { question: "What should the next festival be called?", options: ["Palm Night", "Camel Moon", "Golden Dune"], kind: "name", ...extra }, hs[n]);
ok((await mkPoll("dina")).error === "poll.noRight", "only the Emperor (or the owner) opens a vote");
ok((await mkPoll("alice", { options: ["only one"] })).error === "poll.bad", "2 to 5 options");
let pr = await mkPoll("alice");
ok(pr.ok, "the Emperor opens a vote");
ok((await mkPoll("alice")).error === "poll.open", "one open vote at a time");
const pl = await get("/api/decrees", hs.dina);
const pid = pl.open[0].id;
ok(pl.open.length === 1 && pl.open[0].options.length === 3 && pl.canCreate === false && pl.weight === 13, "everyone sees it; dina (12 Pi paid) weighs 13", pl.weight);
ok((await post("/api/decrees/vote", { id: pid, opt: 1 }, hs.dina)).ok, "dina votes for option 2");
ok((await post("/api/decrees/vote", { id: pid, opt: 0 }, hs.dina)).error === "poll.voted", "one vote each");
await post("/api/decrees/vote", { id: pid, opt: 0 }, hs.fatima); // fatima paid nothing: weight 1
await post("/api/decrees/vote", { id: pid, opt: 0 }, hs.emad);   // emad paid 15 in total (5 + the House): weight 16
let v = (await get("/api/decrees", hs.fatima)).open[0];
ok(v.tally[0] === 17 && v.tally[1] === 13 && v.voters === 3 && v.mine === 0, "weighted tally: payers count more, non-payers 1", v.tally);
await exec(`UPDATE decrees SET closes_at = ${Date.now() - 1000} WHERE id = ${pid}`);
const res = await (await fetch(B + "/api/decrees/results")).json();
ok(res.results.length === 1 && res.results[0].winnerText === "Palm Night", "after 3 days the result is public: Palm Night");
ok((await post("/api/decrees/vote", { id: pid, opt: 1 }, hs.bob)).error === "poll.gone", "closed votes accept nothing");
// ---- Parliament elections (the date is fixed for the test) ----
const setNow = (d) => fetch(B + "/__test/env", { method: "POST", body: JSON.stringify({ key: "COURT_NOW", value: String(Date.UTC(2027, 0, d, 12)) }) });
await setNow(3);
let el = await get("/api/election", hs.dina);
ok(el.phase === "candidacy" && el.canRun === true, "days 1-7: candidacy");
ok((await post("/api/election/run", { speech: "Water for all" }, hs.fatima)).error === "el.supporters", "only supporters can run");
await post("/api/election/run", { speech: "Water for all" }, hs.dina); await post("/api/election/run", { speech: "More camels" }, hs.carol); await post("/api/election/run", { speech: "Free dates" }, hs.emad);
ok((await post("/api/election/vote", { uid: U.dina }, hs.bob)).error === "el.phase", "no voting during candidacy");
await setNow(9);
el = await get("/api/election", hs.dina);
ok(el.phase === "voting" && el.candidates.length === 3, "days 8-14: voting", el.phase);
ok((await post("/api/election/run", { speech: "late" }, hs.bob)).error === "el.phase", "too late to run");
ok((await post("/api/election/vote", { uid: U.dina }, hs.dina)).error === "el.self", "no self vote");
await post("/api/election/vote", { uid: U.carol }, hs.bob); await post("/api/election/vote", { uid: U.carol }, hs.alice); await post("/api/election/vote", { uid: U.dina }, hs.fatima);
ok((await post("/api/election/vote", { uid: U.emad }, hs.bob)).error === "el.voted", "one vote each");
await setNow(16);
el = await get("/api/election", hs.dina);
ok(el.phase === "results" && el.parliament.members.length === 3 && el.parliament.members[0].username === "carol" && el.parliament.members[0].seat === 1, "from the 15th: carol is Speaker (votes weigh Pi)", el.parliament.members);
ok(el.parliament.members.map((m) => m.username).join() === "carol,dina,emad", "seats by votes: carol, dina, emad");
await exec(`DELETE FROM court_gifts`);
r = await claim("carol");
ok(r.ok && r.parts.parliament === 2000, "the Speaker gets 2,000 coins a day on top of the title", r.parts);
r = await claim("dina");
ok(r.ok && r.parts.parliament === 1000, "an MP gets 1,000", r.parts);
await fetch(B + "/__test/env", { method: "POST", body: JSON.stringify({ key: "COURT_NOW", value: null }) });
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
