// Garage (cars bought with dates) and collector cars (Pi). Fresh harness.
const B = "http://localhost:3457";
const post = (p, b, tok) => fetch(B + p, { method: "POST", headers: { "Content-Type": "application/json", ...(tok ? { Authorization: "Bearer " + tok } : {}) }, body: typeof b === "string" ? b : JSON.stringify(b) }).then((r) => r.json());
const get = (p, tok) => fetch(B + p, { headers: tok ? { Authorization: "Bearer " + tok } : {} }).then((r) => r.json());
const sql = (q) => post("/__test/sql", q);
const exec = (q) => fetch(B + "/__test/exec", { method: "POST", body: q });
let pass = 0, fail = 0;
const ok = (c, m, x) => { console.log((c ? "PASS  " : "FAIL  ") + m + (c || x === undefined ? "" : " -> " + JSON.stringify(x))); c ? pass++ : fail++; };
global.window = global; await import("../public/logic.js"); await import("../public/kombat-logic.js");
const L = globalThis.OasisLogic, KL = globalThis.KombatLogic, GR = L.GARAGE, CR = L.CARS;
ok(GR.CARS.length === 10 && CR.TIERS.length === 10, "10 garage cars and 10 collector cars");
ok(CR.TIERS.every((c) => { const k = KL.nftById("car" + c.n); return k && k.pi === c.price && k.perk === c.perk && k.max === c.max; }), "collector car data matches the Kombat collectibles (price, perk, copies)");
ok(GR.CARS.every((c, i) => !i || (c.price > GR.CARS[i - 1].price && c.b > GR.CARS[i - 1].b)), "better garage cars cost more");
const C = (await post("/api/auth", { accessToken: "tokC" })).session, D = (await post("/api/auth", { accessToken: "tokD" })).session;
const uC = (await sql("SELECT uid FROM users WHERE username='carol'"))[0].uid, uD = (await sql("SELECT uid FROM users WHERE username='dina'"))[0].uid;
await post("/api/me", {}, C); await post("/api/me", {}, D);
const dates = async (u) => Number((await sql(`SELECT json_extract(json,'$.dates') AS d FROM state WHERE uid='${u}'`))[0].d);
const act = (a, tok = C) => post("/api/action", { action: a }, tok);
await exec(`UPDATE state SET json = json_set(json, '$.dates', 100000), ver = ver + 1 WHERE uid='${uC}'`);
let r = await act({ type: "gBuy", id: "g1" });
ok(r.state && r.state.garage.own.g1 === 1 && (await dates(uC)) === 50000, "buying a garage car costs its price in dates", r.error);
ok((await act({ type: "gBuy", id: "g1" })).error === "badAction", "you can't buy the same car twice");
ok((await act({ type: "gBuy", id: "g9" })).error === "notEnough", "not enough dates is refused");
ok((await act({ type: "gBuy", id: "nope" })).error === "badAction", "unknown car refused");
r = await act({ type: "gUp", id: "g1" });
ok(r.state && r.state.garage.own.g1 === 2 && (await dates(uC)) === 25000, "upgrading to level 2 costs half the price", r.error);
await act({ type: "gUp", id: "g1" }).catch(() => {});
ok((await dates(uC)) >= 0, "dates never go negative");
// cap and bonus
const allOwn = JSON.stringify(Object.fromEntries(GR.CARS.map((c) => [c.id, 3])));
ok(GR.bonus({ garage: { own: JSON.parse(allOwn) } }) === GR.CAP, "the total bonus is capped at 30%");
await exec(`UPDATE state SET json = json_set(json, '$.garage.own', json('${allOwn}'), '$.lastDaily', -1, '$.dates', 0, '$.xp', 0), ver = ver + 1 WHERE uid='${uC}'`);
r = await act({ type: "daily" });
const s = (await sql(`SELECT json FROM state WHERE uid='${uC}'`)).map((x) => JSON.parse(x.json))[0];
ok(r.state && s.dates === L.C.DAILY + Math.floor(L.C.DAILY * GR.CAP) && s.xp === L.C.DAILY, "the garage bonus adds dates to the daily gift but not to the level XP", [s.dates, s.xp]);
// collector cars
const pay = async (id, uid, amount, tier, h) => {
  await fetch(B + "/__test/pay", { method: "POST", body: JSON.stringify({ id, uid, amount, type: "car", tier, txid: "t" + id }) });
  const a = await post("/api/payments/approve", { paymentId: id }, h); if (a.error) return a;
  return post("/api/payments/complete", { paymentId: id, txid: "t" + id }, h);
};
ok((await pay("c0", uC, 5, 3, C)).error === "badPayment", "wrong amount for the car is refused");
ok((await pay("c00", uC, 8, 11, C)).error === "badPayment", "there is no car 11");
const d0 = await dates(uC), j0 = Number((await sql(`SELECT COALESCE(jry_pts,0) AS j FROM users WHERE uid='${uC}'`))[0].j);
r = await pay("c1", uC, 8, 3, C);
const B3 = CR.bundle(3);
ok(!r.error && (await dates(uC)) - d0 === B3.dates && Number((await sql(`SELECT COALESCE(jry_pts,0) AS j FROM users WHERE uid='${uC}'`))[0].j) - j0 === B3.jry, "a collector car pays its fixed bundle", [await dates(uC) - d0, B3]);
ok((await sql(`SELECT edition FROM nft_items WHERE owner='${uC}' AND kind='car3'`))[0].edition === 1, "numbered card #1 is minted");
await pay("c2", uD, 8, 3, D);
ok((await sql(`SELECT edition FROM nft_items WHERE owner='${uD}' AND kind='car3'`))[0].edition === 2, "the next buyer gets #2");
await post("/api/payments/complete", { paymentId: "c1", txid: "tc1" }, C);
ok((await sql("SELECT COUNT(*) AS n FROM nft_items WHERE kind='car3'"))[0].n === 2, "completing twice does not mint twice");
ok((await post("/api/nft/mint", { kind: "car3" }, C)).error === "k.nftPaid", "collector cars can't be minted with coins");
const mine = (await get("/api/nft", C)).mine.filter((x) => x.kind === "car3");
ok(mine.length === 1, "the car is in my collection (tradable like other collectibles)");
await exec(`INSERT INTO car_counter (tier, n) VALUES (10, 50) ON CONFLICT(tier) DO UPDATE SET n = 50`);
ok((await pay("c3", uC, 100, 10, C)).error === "car.soldout", "a sold-out car cannot be bought");
const info = await get("/api/cars", C);
ok(info.minted["3"] === 2 && info.mine.length === 1 && info.mine[0].tier === 3, "GET /api/cars lists sold copies and my cars", info);
console.log(`== ${pass} passed, ${fail} failed`);
