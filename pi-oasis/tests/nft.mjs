// Jerry Collectibles. Start tests/harness.mjs first.
const B = "http://localhost:3457";
const post = (p, b, h = {}) => fetch(B + p, { method: "POST", headers: { "Content-Type": "application/json", ...h }, body: typeof b === "string" ? b : JSON.stringify(b) }).then((r) => r.text().then((t) => { try { return { s: r.status, ...JSON.parse(t) }; } catch { return { s: r.status, t }; } }));
let pass = 0, fail = 0;
const ok = (c, m) => { console.log((c ? "PASS  " : "FAIL  ") + m); c ? pass++ : fail++; };
const sql = (q) => post("/__test/sql", q).then((r) => { const { s, ...rest } = r; return Object.values(rest); });
const exec = (q) => post("/__test/exec", q);
const A = (await post("/api/auth", { accessToken: "tokA" })).session, Bo = (await post("/api/auth", { accessToken: "tokB" })).session;
const HA = { Authorization: "Bearer " + A }, HB = { Authorization: "Bearer " + Bo };
await post("/api/action", { action: { type: "kSync" } }, HA); await post("/api/action", { action: { type: "kSync" } }, HB);
const uid = async (n) => (await sql(`SELECT uid FROM users WHERE username='${n}'`))[0].uid;
const uA = await uid("alice"), uB = await uid("bob");
const setCoins = (u, n) => exec(`UPDATE state SET json = json_set(json, '$.kombat.coins', ${n}) WHERE uid='${u}'`);
const coins = async (u) => JSON.parse((await sql(`SELECT json FROM state WHERE uid='${u}'`))[0].json).kombat.coins;

ok((await post("/api/nft/mint", { kind: "palm" }, HA)).error === "k.noCoins", "can't mint without enough coins");
await setCoins(uA, 30000000);
let r = await post("/api/nft/mint", { kind: "palm" }, HA);
ok(r.item && r.item.edition === 1 && r.state.kombat.coins === 30000000 - 20000, "alice mints Golden Palm #1 for 20,000");
r = await post("/api/nft/mint", { kind: "palm" }, HA);
ok(r.item.edition === 2, "next copy is #2");
r = await post("/api/nft/mint", { kind: "star" }, HA);
ok(r.item && r.item.edition === 1, "the only Pi Star #1/1 minted");
await setCoins(uB, 50000000);
ok((await post("/api/nft/mint", { kind: "star" }, HB)).error === "k.nftSoldOut", "Pi Star sold out for everyone else");
let me = await fetch(B + "/api/me", { headers: HA }).then((x) => x.json());
ok(Math.abs(me.account.nftBoost - 0.26) < 1e-9, "alice owns 2 designs (palm +1%, star +25%): +26% profit/hour (2 palms count once)");
const nd = await fetch(B + "/api/nft", { headers: HA }).then((x) => x.json());
const star = nd.mine.find((x) => x.kind === "star");
ok(nd.minted.palm === 2 && nd.minted.star === 1 && nd.mine.length === 3, "catalog counts and alice's collection");
ok((await post("/api/nft/list", { id: star.id, price: 30000000 }, HB)).error === "k.nftNotYours", "bob can't list alice's copy");
ok((await post("/api/nft/list", { id: star.id, price: 0 }, HA)).error === "k.nftPrice", "price must be at least 1");
await post("/api/nft/list", { id: star.id, price: 30000000 }, HA);
ok((await post("/api/nft/buy", { id: star.id, price: 30000000 }, HA)).error === "k.nftOwn", "can't buy your own listing");
ok((await post("/api/nft/buy", { id: star.id, price: 1 }, HB)).error === "k.nftGone", "a stale price is refused");
await setCoins(uB, 1000);
ok((await post("/api/nft/buy", { id: star.id, price: 30000000 }, HB)).error === "k.noCoins", "bob needs enough coins");
await setCoins(uB, 50000000);
const a0 = await coins(uA);
r = await post("/api/nft/buy", { id: star.id, price: 30000000 }, HB);
ok(r.state && r.state.kombat.coins === 20000000, "bob buys the Pi Star for 30,000,000");
ok((await post("/api/nft/buy", { id: star.id, price: 30000000 }, HB)).error === "k.nftGone", "it can't be bought twice");
me = await fetch(B + "/api/me", { headers: HA }).then((x) => x.json());
ok(me.state.kombat.coins === a0 + 28500000 && me.state.kombat.earn.trade === 28500000, "alice receives 28,500,000 (95%; 5% burned) when she comes back");
me = await fetch(B + "/api/me", { headers: HA }).then((x) => x.json());
ok(me.state.kombat.coins === a0 + 28500000, "the sale money is added only once");
const mb = await fetch(B + "/api/me", { headers: HB }).then((x) => x.json());
ok(Math.abs(mb.account.nftBoost - 0.25) < 1e-9 && Math.abs(me.account.nftBoost - 0.01) < 1e-9, "perks follow the owner: bob +25%, alice +1%");
const nd2 = await fetch(B + "/api/nft").then((x) => x.json());
ok(nd2.recent.length === 1 && nd2.recent[0].seller === "alice" && nd2.recent[0].buyer === "bob" && nd2.market.length === 0, "sale history: alice → bob; market empty");
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
