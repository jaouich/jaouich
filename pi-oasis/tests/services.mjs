// Jerry Development services (app requests). Start tests/harness.mjs first.
const B = "http://localhost:3457";
const post = (p, b, h = {}) => fetch(B + p, { method: "POST", headers: { "Content-Type": "application/json", ...h }, body: JSON.stringify(b) }).then((r) => r.text().then((t) => { try { return { s: r.status, ...JSON.parse(t) }; } catch { return { s: r.status, t }; } }));
const get = (p, h) => fetch(B + p, { headers: h }).then((r) => r.json());
const notifs = () => fetch(B + "/__test/notifs").then((r) => r.json());
let pass = 0, fail = 0;
const ok = (c, m) => { console.log((c ? "PASS  " : "FAIL  ") + m); c ? pass++ : fail++; };
const H = async (tok, lang) => ({ Authorization: "Bearer " + (await post("/api/auth", { accessToken: tok, lang })).session });
const HA = await H("tokA", "ar"), HB = await H("tokB", "fr");
let r = await get("/api/svc");
ok(r.packs.length === 4 && r.packs[0].from === 10000 && r.mine.length === 0, "4 packages with their 'from' price");
ok((await post("/api/svc/request", { pkg: "game", name: "Bob", idea: "short" }, HB)).error === "svc.short", "idea too short refused");
ok((await post("/api/svc/request", { pkg: "nope", name: "Bob", idea: "x".repeat(40) }, HB)).error === "badAction", "unknown package refused");
ok((await post("/api/svc/request", { pkg: "custom", name: "Bob", idea: "A casino app with bets for everyone in Pi" }, HB)).error === "sp.rules", "forbidden topics refused");
const n0 = (await notifs()).length;
r = await post("/api/svc/request", { pkg: "game", name: "Bob Shop", idea: "A farming game for my community\nwith Pi payments and a weekly ranking.", budget: "40,000 Pi", contact: "@bob_tg <b>" }, HB);
ok(r.ok && r.id, "request sent");
const nn = (await notifs()).slice(n0);
ok(nn.length === 1 && nn[0].user_uid === "uA" && nn[0].title === "🛠️ طلب تطبيق جديد" && nn[0].subroute === "/?go=services", "the owner gets a Pi notification (in his language) that opens the services page");
r = await get("/api/svc", HB);
ok(r.mine.length === 1 && r.mine[0].status === "new" && r.mine[0].contact === undefined, "the client sees his request (status only)");
for (let i = 0; i < 2; i++) await post("/api/svc/request", { pkg: "site", name: "Bob", idea: "Another idea for a Pi app number " + i }, HB);
ok((await post("/api/svc/request", { pkg: "site", name: "Bob", idea: "One more idea for a Pi app here" }, HB)).error === "svc.tooMany", "max 3 open requests");
ok((await post("/api/admin/svc", { action: "list" }, HB)).s === 403, "only the owner sees all requests");
r = await post("/api/admin/svc", { action: "list" }, HA);
const first = r.list.find((x) => x.pkg === "game");
ok(r.list.length === 3 && first.contact === "@bob_tg b" && first.idea.includes("\n"), "owner sees the full request (contact cleaned, line breaks kept)");
const n1 = (await notifs()).length;
r = await post("/api/admin/svc", { action: "status", id: first.id, status: "talking", note: "Let's talk on Telegram" }, HA);
ok(r.list.find((x) => x.id === first.id).status === "talking", "owner sets the status");
const up = (await notifs()).slice(n1);
ok(up.length === 1 && up[0].user_uid === "uB" && up[0].title.startsWith("🛠️ Ta demande"), "the client is told (in French)");
r = await get("/api/svc", HB);
ok(r.mine.find((x) => x.id === first.id).note === "Let's talk on Telegram", "the client sees the owner's note");
ok((await post("/api/admin/svc", { action: "status", id: first.id, status: "weird" }, HA)).error === "badAction", "unknown status refused");
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
