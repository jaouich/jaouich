// Login streak and achievements. Fresh harness.
const B = "http://localhost:3457";
const post = (p, b, tok) => fetch(B + p, { method: "POST", headers: { "Content-Type": "application/json", ...(tok ? { Authorization: "Bearer " + tok } : {}) }, body: typeof b === "string" ? b : JSON.stringify(b) }).then((r) => r.json());
const get = (p, tok) => fetch(B + p, { headers: tok ? { Authorization: "Bearer " + tok } : {} }).then((r) => r.json());
const sql = (q) => post("/__test/sql", q);
const exec = (q) => fetch(B + "/__test/exec", { method: "POST", body: q });
let pass = 0, fail = 0;
const ok = (c, m, x) => { console.log((c ? "PASS  " : "FAIL  ") + m + (c || x === undefined ? "" : " -> " + JSON.stringify(x))); c ? pass++ : fail++; };
global.window = global; await import("../public/logic.js"); const L = globalThis.OasisLogic;
const C = (await post("/api/auth", { accessToken: "tokC" })).session;
const uid = (await sql("SELECT uid FROM users WHERE username='carol'"))[0].uid;
const today = Math.floor(Date.now() / 86400000);
const jry = async () => (await sql(`SELECT COALESCE(jry_pts,0) AS j FROM users WHERE uid='${uid}'`))[0].j;
const dates = async () => (await sql(`SELECT json_extract(json,'$.dates') AS d FROM state WHERE uid='${uid}'`))[0].d;
await post("/api/me", {}, C);
let s = await get("/api/streak", C);
ok(s.n === 0 && !s.claimed && s.day === 1, "new player: streak 0, day 1 to claim", s);
const d0 = await dates();
let r = await post("/api/streak/claim", {}, C);
ok(r.ok && r.n === 1 && r.dates === 100 && (await dates()) - d0 === 100, "day 1 pays 100 dates", r);
r = await post("/api/streak/claim", {}, C);
ok(r.error || r.code, "only one claim per day", r);
s = await get("/api/streak", C);
ok(s.claimed && s.day === 1 && s.n === 1, "status after claim", s);
await exec(`UPDATE login_streak SET last = ${today - 1}, n = 6 WHERE uid='${uid}'`);
const j0 = await jry();
r = await post("/api/streak/claim", {}, C);
ok(r.n === 7 && r.day === 7 && r.dates === 1000 && r.jry === 20 && (await jry()) - j0 === 20, "day 7 pays 1000 dates + 20 JRY points + spin", r);
await exec(`UPDATE login_streak SET last = ${today - 3}, n = 12 WHERE uid='${uid}'`);
s = await get("/api/streak", C);
ok(s.n === 0 && s.day === 1, "a missed day resets the streak", s);
r = await post("/api/streak/claim", {}, C);
ok(r.n === 1 && r.day === 1, "restarts at day 1");
await exec(`UPDATE login_streak SET last = ${today - 1}, n = 7 WHERE uid='${uid}'`);
r = await post("/api/streak/claim", {}, C);
ok(r.n === 8 && r.day === 1, "day 8 starts a new week of rewards", r);
// achievements
let a = await get("/api/ach", C);
ok(a.list.length === L.ACH.length && a.list.every((x) => !x.claimed), "achievement list", a.list.length);
await exec(`UPDATE state SET json = json_set(json, '$.xp', ${L.LV.need(10)}, '$.merge.merges', 3) WHERE uid='${uid}'`);
a = await get("/api/ach", C);
const done = a.list.filter((x) => x.done).map((x) => x.id);
ok(done.includes("lv5") && done.includes("lv10") && done.includes("merge1") && !done.includes("lv20"), "conditions come from the server state", done);
const j1 = await jry();
r = await post("/api/ach/claim", {}, C);
ok(r.ok && r.got === done.length && (await jry()) - j1 === 10 * done.length, "claim pays 10 JRY points each", [r, (await jry()) - j1]);
r = await post("/api/ach/claim", {}, C);
ok(r.error || r.code, "achievements pay once");
console.log(`== ${pass} passed, ${fail} failed`);
